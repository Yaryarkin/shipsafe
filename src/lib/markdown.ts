import { displayTarget, isBuildTarget } from "@/lib/scan-target";
import { CATEGORY_LABELS, type ScanResult, type Severity } from "@/lib/scanner/types";

const SEVERITY_LABEL: Record<Severity, string> = {
  critical: "CRITICAL",
  warning: "WARNING",
  info: "INFO",
  passed: "PASSED",
};

function fence(content: string, lang = ""): string {
  // Use a fence longer than any backtick run inside the content.
  const longestRun = Math.max(2, ...(content.match(/`+/g) ?? []).map((run) => run.length));
  const ticks = "`".repeat(longestRun + 1);
  return `${ticks}${lang}\n${content}\n${ticks}`;
}

export function reportToMarkdown(result: ScanResult): string {
  const host = displayTarget(result.target);
  const lines: string[] = [
    `# ShipSafe Security Report — ${host}`,
    "",
    ...(isBuildTarget(result.target)
      ? [`- **Build:** ${host} (scanned locally in the browser — nothing was uploaded)`]
      : [`- **Target:** ${result.target}`, `- **Final URL:** ${result.finalUrl}`]),
    `- **Scanned at:** ${new Date(result.scannedAt).toUTCString()}`,
    `- **Scan duration:** ${(result.scanDurationMs / 1000).toFixed(1)}s`,
    `- **Score:** ${result.overallScore}/100 (Grade ${result.grade})`,
    "",
    "| Critical | Warning | Info | Passed |",
    "| --- | --- | --- | --- |",
    `| ${result.summary.critical} | ${result.summary.warning} | ${result.summary.info} | ${result.summary.passed} |`,
    "",
    "> Passive configuration check only (standard GET/HEAD requests). Secrets are masked; file contents are never stored.",
    "",
    "## Findings",
    "",
  ];

  result.findings.forEach((item, index) => {
    lines.push(`### ${index + 1}. [${SEVERITY_LABEL[item.severity]}] ${item.title}`);
    lines.push("");
    lines.push(`**Category:** ${CATEGORY_LABELS[item.category]}`);
    lines.push("");
    lines.push(item.description);
    lines.push("");
    if (item.evidence) {
      lines.push("**Evidence**");
      lines.push("");
      lines.push(fence(item.evidence));
      lines.push("");
    }
    if (item.fixPrompt) {
      lines.push("**AI fix prompt** (paste into Cursor / Claude Code)");
      lines.push("");
      lines.push(fence(item.fixPrompt, "text"));
      lines.push("");
    }
  });

  lines.push("---");
  lines.push("Generated by ShipSafe — pre-launch security & config audit.");
  return lines.join("\n");
}

export function downloadMarkdown(result: ScanResult): void {
  const host = displayTarget(result.target).replace(/[^a-z0-9.-]/gi, "_");
  const date = result.scannedAt.slice(0, 10);
  const blob = new Blob([reportToMarkdown(result)], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `shipsafe-report-${host}-${date}.md`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1_000);
}
